import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync, copyFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const repoRoot = resolve(dirname(scriptPath), "..");
const outputPath = join(repoRoot, "packages/server/test-fixtures/entity-metadata-fixtures.ts");
const copiedSpineOptionsPath = join(repoRoot, "proto/spine/options.proto");
const bufExecutable = join(
  repoRoot,
  "node_modules/.bin",
  process.platform === "win32" ? "buf.cmd" : "buf",
);
const fixtureDefinitions = [
  {
    key: "main",
    protoPath: "packages/server/test-fixtures/proto/entity-metadata/main.proto",
  },
  {
    key: "empty",
    protoPath: "packages/server/test-fixtures/proto/entity-metadata/empty.proto",
  },
  {
    key: "unknownKind",
    protoPath: "packages/server/test-fixtures/proto/entity-metadata/unknown-kind.proto",
  },
  {
    key: "invalidColumn",
    protoPath: "packages/server/test-fixtures/proto/entity-metadata/invalid-column.proto",
  },
  {
    key: "invalidTag",
    protoPath: "packages/server/test-fixtures/proto/entity-metadata/invalid-tag.proto",
  },
  {
    key: "visibility",
    protoPath: "packages/server/test-fixtures/proto/entity-metadata/visibility.proto",
  },
];
const checkMode = process.argv.includes("--check");

function main() {
  const generated = renderFixtureModule();

  if (checkMode) {
    const current = readFileSync(outputPath, "utf8");

    if (current !== generated) {
      console.error(
        `Server test fixture descriptors are out of date. Run "node scripts/generate-server-test-fixtures.mjs".`,
      );
      process.exit(1);
    }

    return;
  }

  writeFileSync(outputPath, generated);
}

function renderFixtureModule() {
  const fixtureEntries = fixtureDefinitions.map((fixture) => ({
    ...fixture,
    descriptorSetBase64: buildDescriptorSetBase64(fixture.protoPath),
  }));
  const entries = fixtureEntries
    .map(
      (fixture) => `  ${fixture.key}: Object.freeze({
    protoPath: ${JSON.stringify(fixture.protoPath)},
    descriptorSetBase64:
      ${JSON.stringify(fixture.descriptorSetBase64)},
  }),`,
    )
    .join("\n");
  const sourceList = fixtureDefinitions
    .map((fixture) => ` * - \`${fixture.protoPath}\``)
    .join("\n");

  return `/**
 * Generated by \`node scripts/generate-server-test-fixtures.mjs\`.
 *
 * Readable source fixtures:
${sourceList}
 */

export interface ServerEntityMetadataTestFixture {
  readonly protoPath: string;
  readonly descriptorSetBase64: string;
}

export const serverEntityMetadataFixtureGeneration = Object.freeze({
  command: "node scripts/generate-server-test-fixtures.mjs",
  protoRoot: "packages/server/test-fixtures/proto/entity-metadata",
});

export const serverEntityMetadataTestFixtures = Object.freeze({
${entries}
});
`;
}

function buildDescriptorSetBase64(protoPath) {
  const tempRoot = mkdtempSync(join(tmpdir(), "spine-server-fixtures-"));
  const tempProtoRoot = join(tempRoot, "proto");
  const tempSpineRoot = join(tempProtoRoot, "spine");
  const tempFixturePath = join(
    tempRoot,
    "proto",
    relative("packages/server/test-fixtures/proto", protoPath),
  );
  const tempOutputPath = join(tempRoot, "fixture.binpb");

  mkdirSync(tempSpineRoot, { recursive: true });
  mkdirSync(dirname(tempFixturePath), { recursive: true });
  copyFileSync(copiedSpineOptionsPath, join(tempSpineRoot, "options.proto"));
  copyFileSync(join(repoRoot, protoPath), tempFixturePath);
  writeFileSync(join(tempRoot, "buf.yaml"), `version: v2\nmodules:\n  - path: proto\n`);

  const result = spawnSync(
    bufExecutable,
    [
      "build",
      ".",
      "--as-file-descriptor-set",
      "--exclude-imports",
      "--path",
      relative(tempRoot, tempFixturePath),
      "-o",
      relative(tempRoot, tempOutputPath),
    ],
    {
      cwd: tempRoot,
      encoding: "utf8",
    },
  );

  try {
    if (result.status !== 0) {
      process.stderr.write(result.stderr);
      process.exit(result.status ?? 1);
    }

    return readFileSync(tempOutputPath).toString("base64");
  } finally {
    rmSync(tempRoot, { force: true, recursive: true });
  }
}

main();

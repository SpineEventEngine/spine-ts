import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

import { generatedFileNotice, generatedTypeScript } from "./generated-source-policy.mjs";

describe("generated source policy", () => {
  it("keeps generated TypeScript inventories free of copied copyright and license preambles", () => {
    const roots = [
      "packages/proto/generated",
      "examples/todo/generated",
      "examples/projects/generated",
      "examples/orders/generated",
      "examples/message-board/model/generated",
    ];
    const files = [];
    for (const root of roots) {
      const pending = [join(process.cwd(), root)];
      while (pending.length > 0) {
        const directory = pending.pop();
        for (const entry of readdirSync(directory, { withFileTypes: true })) {
          const path = join(directory, entry.name);
          if (entry.isDirectory()) pending.push(path);
          else if (entry.isFile() && /\.(?:d\.ts|ts)$/u.test(path)) files.push(path);
        }
      }
    }
    for (const file of files)
      expect(readFileSync(file, "utf8")).not.toMatch(
        /copyright|all rights reserved|proprietary and confidential|licensed under/iu,
      );
  });

  it("removes a copied Proto copyright notice while retaining stable provenance", () => {
    const source = [
      "//",
      "// Copyright 2026, CodeMatters. All rights reserved.",
      "//",
      '// Licensed under the Apache License, Version 2.0 (the "License");',
      "// @generated from file spine/example/task.proto",
      "export const Task = true;",
      "",
    ].join("\n");

    expect(generatedTypeScript(source, ["spine/example/task.proto"])).toBe(
      [
        "/*",
        " * Generated by Spine TypeScript. Do not edit manually.",
        " * Source Proto: spine/example/task.proto",
        " */",
        "",
        "// @generated from file spine/example/task.proto",
        "/**",
        " * Generated from Proto: spine/example/task.proto.",
        " */",
        "export const Task = true;",
        "",
      ].join("\n"),
    );
  });

  it("removes copied upstream block and line copyright preambles", () => {
    const source = [
      "/* Copyright 2024 TeamDev Ltd. Licensed under Apache-2.0. */",
      "// Copyright 2023 Upstream Authors",
      "// Licensed under the Apache License, Version 2.0",
      "// @generated from file spine/example/task.proto",
      "export const Task = true;",
      "",
    ].join("\n");

    const generated = generatedTypeScript(source, ["spine/example/task.proto"]);
    expect(generated).not.toMatch(/copyright|TeamDev|Upstream Authors/iu);
    expect(generated).toContain("// @generated from file spine/example/task.proto");
  });

  it("rejects unstable or machine-local Proto provenance", () => {
    for (const value of [
      "",
      "../task.proto",
      "/tmp/task.proto",
      "C:\\work\\task.proto",
      ".generated-stage/task.proto",
      ".stage-123/task.proto",
      ".backup-prior/task.proto",
      "tmp/task.proto",
      "temp/task.proto",
    ]) {
      expect(() => generatedFileNotice([value])).toThrow(/stable Proto provenance/);
    }
    expect(generatedFileNotice(["template/task.proto", "attempt/task.proto"])).toContain(
      "Source Proto: template/task.proto",
    );
  });

  it("documents exported interfaces, enums, types, and constants", () => {
    const source = [
      "export interface Task {}",
      "export enum State { Open }",
      "export type TaskId = string;",
      "export const task = true;",
      "",
    ].join("\n");
    const generated = generatedTypeScript(source, ["spine/example/task.proto"]);
    expect(generated.match(/Generated from Proto:/gu)).toHaveLength(4);
  });

  it("keeps every ignored example Proto module singly noticed and documented", () => {
    for (const example of ["todo", "projects", "orders", "message-board/model"]) {
      const source = readFileSync(
        join(process.cwd(), "examples", example, "generated/proto-module.ts"),
        "utf8",
      );
      expect(source.match(/Generated by Spine TypeScript/gu)).toHaveLength(1);
      expect(source.match(/Generated from Proto:/gu)).toHaveLength(1);
      expect(source).not.toContain("CodeMatters");
      const protoSources = [...source.matchAll(/^ \* Source Proto: (.+)$/gmu)].map(
        (match) => match[1],
      );
      expect(protoSources).not.toContainEqual(expect.stringMatching(/^(?:\/|[A-Za-z]:\\)/u));
      const declaration = readFileSync(
        join(process.cwd(), "examples", example, "dist/generated/proto-module.d.ts"),
        "utf8",
      );
      expect(declaration.match(/Generated by Spine TypeScript/gu)).toHaveLength(1);
      expect(declaration.match(/Generated from Proto:/gu)).toHaveLength(1);
      expect(declaration).not.toContain("CodeMatters");
    }
    const frameworkDeclaration = readFileSync(
      join(process.cwd(), "packages/proto/dist/generated/proto-module.d.ts"),
      "utf8",
    );
    expect(frameworkDeclaration.match(/Generated by Spine TypeScript/gu)).toHaveLength(1);
    expect(frameworkDeclaration.match(/Generated from Proto:/gu)).toHaveLength(1);
    expect(frameworkDeclaration).not.toContain("CodeMatters");

    const appDeclaration = readFileSync(
      join(process.cwd(), "examples/message-board/app/dist/src/model-registry.d.ts"),
      "utf8",
    );
    expect(appDeclaration.match(/Generated by Spine TypeScript/gu)).toHaveLength(1);
    expect(appDeclaration.match(/Generated from Proto:/gu)).toHaveLength(1);
    expect(appDeclaration).not.toContain("CodeMatters");
  });
});
